-- Kurk: database voor de inhoud van de app.
-- Eén keer uitvoeren in Supabase → SQL Editor, daarna seed.sql.
-- Iedereen mag lezen (de app); alleen e-mailadressen in de tabel admins mogen schrijven.

create table stijlen (
  id      text primary key check (id ~ '^[a-z0-9-]+$'),
  naam    text not null,
  sub     text not null default '',
  positie int  not null default 0
);

create table niveaus (
  id      text primary key check (id ~ '^[a-z0-9-]+$'),
  naam    text not null,
  sub     text not null default '',
  positie int  not null default 0
);

create table oefeningen (
  id        text primary key check (id ~ '^[a-z0-9-]+$'),
  titel     text not null,
  soort     text[] not null check (cardinality(soort) > 0 and soort <@ array['op','af']),
  -- categorieën staan vast in de code (ze bepalen de volgorde van een routine)
  cat       text not null check (cat in ('lichaam','adem','sovt','resonantie','bereik','articulatie','stijl','ontspanning','afbouw','rust')),
  duur      int  not null check (duur between 10 and 1800),
  stijlen   text[] not null default array['alle'] check (cardinality(stijlen) > 0),
  niveau    text[],  -- null = voor alle niveaus
  klank     text not null default '—',
  kort      text not null default '',
  stappen   text[] not null default '{}',
  letop     text not null default '',
  waarom    text not null default '',
  video     text not null default '',
  zichtbaar boolean not null default true,  -- false = concept, niet in de app
  positie   bigint generated by default as identity,
  gewijzigd timestamptz not null default now()
);

create table instellingen (
  sleutel text primary key,
  waarde  jsonb not null
);

create table admins (
  email text primary key check (email = lower(email))
);

create function zet_gewijzigd() returns trigger language plpgsql as $$
begin new.gewijzigd = now(); return new; end $$;
create trigger oefeningen_gewijzigd before update on oefeningen for each row execute function zet_gewijzigd();

create function is_admin() returns boolean
  language sql stable security definer set search_path = ''
  as $$ select exists (select 1 from public.admins where email = lower(auth.jwt() ->> 'email')) $$;

-- Rechten -----------------------------------------------------------------
alter table stijlen      enable row level security;
alter table niveaus      enable row level security;
alter table oefeningen   enable row level security;
alter table instellingen enable row level security;
alter table admins       enable row level security;

grant select on stijlen, niveaus, oefeningen, instellingen to anon, authenticated;
grant insert, update, delete on stijlen, niveaus, oefeningen, instellingen to authenticated;
grant select on admins to authenticated;
grant usage on all sequences in schema public to authenticated;
grant execute on function is_admin() to anon, authenticated;

create policy lezen on stijlen      for select using (true);
create policy lezen on niveaus      for select using (true);
create policy lezen on instellingen for select using (true);
create policy lezen on oefeningen   for select using (zichtbaar or public.is_admin());

create policy admin_schrijft on stijlen      for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy admin_schrijft on niveaus      for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy admin_schrijft on oefeningen   for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy admin_schrijft on instellingen for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- een admin mag alleen zien dát hij/zij admin is; de lijst beheer je in het dashboard
create policy zichzelf on admins for select to authenticated using (email = lower(auth.jwt() ->> 'email'));

